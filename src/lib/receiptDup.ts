/**
 * 收據圖片「跨記錄重複」的提示文案。
 *
 * 為什麼要獨立一支：
 *   記帳頁的 `ReceiptImages.vue` 與記錄明細的 `RecordSheet.vue` 各有一份收圖流程
 *   （兩邊的既有圖片來源不同），但**這個提醒必須一模一樣** ——
 *   不然同一件事在兩個地方講法不同，使用者會以為是兩種情況。
 *
 * 規則（0.1.22 使用者指定）：
 *   - 同一筆記錄內重複 → 靜默略過（不提示）
 *   - 不同記錄之間重複 → 允許，但要提醒「可能重複記帳」
 */
export function dupNotice(count: number): string {
  return count > 1
    ? `有 ${count} 張圖片和其他記錄重複了，可能重複記帳`
    : '這張圖片和其他記錄重複了，可能重複記帳'
}
